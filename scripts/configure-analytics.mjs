#!/usr/bin/env node
// Package-time configuration only. Never print the write secret or endpoint.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

export function analyticsConfigFromEnv(env) {
  const measurementId = env.GA4_MEASUREMENT_ID || '';
  const apiSecret = env.GA4_API_SECRET || '';
  if (!/^G-[A-Z0-9]+$/.test(measurementId) || !/^[A-Za-z0-9_-]{10,100}$/.test(apiSecret)) {
    throw new Error('Set GA4_MEASUREMENT_ID and GA4_API_SECRET to a valid GA4 web stream and Measurement Protocol secret.');
  }
  if (env.GA4_DEBUG && !['true', 'false'].includes(env.GA4_DEBUG)) throw new Error('GA4_DEBUG must be true or false.');
  return { measurementId, apiSecret, debug: env.GA4_DEBUG === 'true' };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const config = analyticsConfigFromEnv(process.env);
    const output = new URL('../src/utils/analytics-config.js', import.meta.url);
    writeFileSync(output, '// Generated by scripts/configure-analytics.mjs; values are visible in the shipped extension.\n' +
      `export const ANALYTICS_CONFIG = Object.freeze(${JSON.stringify(config, null, 2)});\n`);
    console.log(`Analytics configured (${config.debug ? 'development DebugView' : 'production'}).`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
